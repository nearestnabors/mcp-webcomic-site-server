#!/usr/bin/env node
/**
 * Embed MCP App HTML into a TypeScript file for Netlify Functions
 *
 * This script reads the built HTML files and creates a TypeScript module
 * that exports them as string constants. This ensures the HTML is bundled
 * with the Netlify Function at build time.
 *
 * Run: node scripts/embed-mcp-apps.js
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT = path.join(__dirname, '..');

const files = {
  mcpAppHtml: path.join(ROOT, 'mcp-app/dist/index.html'),
};

const outputPath = path.join(ROOT, 'netlify/functions/embedded-apps.ts');

let output = `// AUTO-GENERATED by scripts/embed-mcp-apps.js
// Do not edit manually - run: node scripts/embed-mcp-apps.js

`;

for (const [varName, filePath] of Object.entries(files)) {
  if (fs.existsSync(filePath)) {
    const content = fs.readFileSync(filePath, 'utf-8');
    // Escape backticks and ${} for template literal
    const escaped = content
      .replace(/\\/g, '\\\\')
      .replace(/`/g, '\\`')
      .replace(/\$\{/g, '\\${');
    output += `export const ${varName} = \`${escaped}\`;\n\n`;
    console.log(`✓ Embedded ${varName} (${content.length} bytes)`);
  } else {
    output += `export const ${varName}: string | null = null;\n\n`;
    console.log(`✗ Missing ${filePath}`);
  }
}

fs.writeFileSync(outputPath, output);
console.log(`\nWritten to ${outputPath}`);
